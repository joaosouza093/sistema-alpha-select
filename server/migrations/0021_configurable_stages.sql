-- =====================================================================
-- Etapas configuráveis pelo administrador: renomear, criar, reordenar,
-- desativar e excluir (só quando nunca usada). A etapa de aprovação é
-- marcada (is_approval) em vez de identificada pela chave. As regras do
-- quadro passam a considerar só as etapas ativas, na ordem:
--   - novo candidato entra na primeira etapa ativa;
--   - sair da primeira etapa ativa = enviado ao cliente;
--   - sem ser administrador, só para a etapa ativa anterior ou seguinte;
--   - aprovação só na etapa de aprovação.
-- =====================================================================

alter table stages
  add column is_active   boolean not null default true,
  add column is_approval boolean not null default false;
update stages set is_approval = true where key = 'aprovacao';
create unique index stages_one_approval on stages (is_approval) where is_approval;
alter table stages add constraint stages_name_check check (char_length(btrim(name)) between 2 and 40);
alter table stages add constraint stages_approval_active check (not is_approval or is_active);
-- Reordenar troca posições dentro de uma transação.
alter table stages drop constraint stages_position_key;
alter table stages add constraint stages_position_key unique (position) deferrable initially deferred;
alter table stages alter column id add generated by default as identity (start with 100);

-- Primeira etapa ativa e posição relativa entre etapas ativas.
create or replace function app.first_stage() returns smallint
language sql stable set search_path = public, pg_temp as $$
  select id from stages where is_active order by position limit 1
$$;
create or replace function app.stage_rank(p_stage smallint) returns int
language sql stable set search_path = public, pg_temp as $$
  select count(*)::int from stages s, stages t where t.id = p_stage and s.is_active and s.position <= t.position
$$;

create or replace function app.tg_applications_guard() returns trigger
language plpgsql set search_path = public, pg_temp as $$
declare
  v_status process_status;
  v_is_app boolean := current_user = 'alpha_app';
begin
  select status into v_status from processes where id = new.process_id;

  if tg_op = 'INSERT' then
    if v_status <> 'em_andamento' then
      raise exception 'Somente processos em andamento aceitam novos candidatos.' using errcode = 'AS409';
    end if;
    if v_is_app then
      new.stage_id := app.first_stage();
      new.decision := 'pendente';
      new.created_by := app.uid();
    end if;
    new.version := 1;
    if new.owner_id is not null and not app.valid_owner(new.process_id, new.owner_id) then
      raise exception 'O responsável precisa ter acesso ativo ao processo.' using errcode = 'AS422';
    end if;
    return new;
  end if;

  -- UPDATE
  if new.candidate_id <> old.candidate_id or new.process_id <> old.process_id then
    raise exception 'Candidato e processo da participação não podem ser alterados.' using errcode = 'AS422';
  end if;

  if v_status <> 'em_andamento' and v_is_app then
    raise exception 'Processo concluído ou arquivado não aceita alterações.' using errcode = 'AS409';
  end if;

  if v_is_app then
    if (new.share_email, new.share_phone, new.share_salary, new.shared_summary)
       is distinct from (old.share_email, old.share_phone, old.share_salary, old.shared_summary)
       and not (app.is_alpha() and app.can_view_process(new.process_id)) then
      raise exception 'Sem permissão para alterar o compartilhamento.' using errcode = 'AS403';
    end if;
    if new.stage_id <> old.stage_id and not app.member_perm(new.process_id, 'move') then
      raise exception 'Sem permissão para alterar a etapa.' using errcode = 'AS403';
    end if;
    if new.decision <> old.decision and not app.member_perm(new.process_id, 'decide') then
      raise exception 'Sem permissão para registrar decisão.' using errcode = 'AS403';
    end if;
    if new.owner_id is distinct from old.owner_id
       and not (app.is_admin()
                or (app.is_alpha() and app.is_member(new.process_id))
                or app.member_perm(new.process_id, 'move')) then
      raise exception 'Sem permissão para alterar o responsável.' using errcode = 'AS403';
    end if;
  end if;

  if new.stage_id <> old.stage_id then
    if new.decision <> 'pendente' then
      raise exception 'Reabra a decisão (pendente) antes de mover o candidato de etapa.' using errcode = 'AS409';
    end if;
    if not exists (select 1 from stages where id = new.stage_id and is_active) then
      raise exception 'Etapa desativada.' using errcode = 'AS422';
    end if;
    if abs(app.stage_rank(new.stage_id) - app.stage_rank(old.stage_id)) <> 1
       and exists (select 1 from stages where id = old.stage_id and is_active)
       and not (app.is_admin() or not v_is_app) then
      raise exception 'Movimentação permitida apenas para a etapa anterior ou seguinte.' using errcode = 'AS422';
    end if;
    new.stage_changed_at := now();
  end if;

  if new.decision = 'aprovado' and new.decision <> old.decision
     and not exists (select 1 from stages where id = new.stage_id and is_approval) then
    raise exception 'A aprovação só pode ser registrada na etapa de aprovação.' using errcode = 'AS422';
  end if;

  if new.owner_id is distinct from old.owner_id and new.owner_id is not null
     and not app.valid_owner(new.process_id, new.owner_id) then
    raise exception 'O responsável precisa ter acesso ativo ao processo.' using errcode = 'AS422';
  end if;

  new.version := old.version + 1;
  new.updated_at := now();
  return new;
end $$;

create or replace function app.tg_applications_sent() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if new.sent_at is null and new.stage_id <> old.stage_id and new.stage_id <> app.first_stage() then
    new.sent_at := now();
    new.sent_by := app.uid();
  end if;
  if old.sent_at is not null and new.sent_at is distinct from old.sent_at then
    raise exception 'O envio ao cliente não pode ser desfeito.' using errcode = 'AS409';
  end if;
  return new;
end $$;

-- Somente o administrador altera as etapas.
create policy stages_insert on stages for insert to alpha_app with check (app.is_admin());
create policy stages_update on stages for update to alpha_app using (app.is_admin()) with check (app.is_admin());
create policy stages_delete on stages for delete to alpha_app using (app.is_admin());
grant insert (key, name, position, is_active) on stages to alpha_app;
grant update (name, position, is_active) on stages to alpha_app;
grant delete on stages to alpha_app;

revoke all on function app.first_stage(), app.stage_rank(smallint) from public;
grant execute on function app.first_stage(), app.stage_rank(smallint) to alpha_app;
do $$
declare r text;
begin
  foreach r in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = r) then
      execute format('revoke all on function app.first_stage(), app.stage_rank(smallint) from %I', r);
    end if;
  end loop;
end $$;
